// IDEOLOGY CENTRALITY
Q.calculateEconomicIdeologyCentrality = function(party, economicCoordinate) {
    var available = Q.getAvailableIdeologies(party);
    if (available.length == 0) {
        return 0;
    }
    var entry = Q.getClosestIdeologyEntry(available, economicCoordinate);
    if (!entry) {
        return 0;
    }
    var definition = Q.getFactionDefinition(entry.faction);
    var anchor = Q.factionEconomicCoordinates[definition.originParty][definition.faction];
    var neighbouringDistances = [];
    for (var otherEntry of available) {
        if (otherEntry.faction == entry.faction) {
            continue;
        }
        var otherDefinition = Q.getFactionDefinition(otherEntry.faction);
        if (!otherDefinition) {
            continue;
        }
        var otherTable = Q.factionEconomicCoordinates[otherDefinition.originParty];
        if (otherTable && otherTable[otherDefinition.faction] !== undefined) {
            neighbouringDistances.push(Math.abs(otherTable[otherDefinition.faction] - anchor));
        }
    }
    if (neighbouringDistances.length == 0) {
        return 100;
    }
    var regionSize = Math.min.apply(null, neighbouringDistances);
    if (regionSize <= 0) {
        return 100;
    }
    var distance = Math.abs(economicCoordinate - anchor);
    return Math.max(0, Math.min(100, 100 - (distance / regionSize) * 100));
};
Q.calculateSocietalIdeologyCentrality = function(party, societalCoordinate) {
    var range = Q.partySocietalRanges[party];
    if (!range) {
        return 0;
    }
    var band = Q.getSocietalIdeologyBand(party, societalCoordinate);
    if (band === null) {
        return 0;
    }
    var weights = Q.partySocietalBandWeights[party];
    var minimum = range[0];
    var maximum = range[1];
    var span = maximum - minimum;
    var relative = (societalCoordinate - minimum) / span;
    relative = Math.max(0, Math.min(1, relative));
    var lower;
    var upper;
    if (band == 0) {
        lower = 0;
        upper = weights[0];
    }
    else if (band == 1) {
        lower = weights[0];
        upper = weights[0] + weights[1];
    }
    else {
        lower = weights[0] + weights[1];
        upper = 1;
    }
    var midpoint = (lower + upper) / 2;
    var halfWidth = (upper - lower) / 2;
    if (halfWidth <= 0) {
        return 100;
    }
    return Math.max(0, Math.min(100, 100 - (Math.abs(relative - midpoint) / halfWidth) * 100));
};
Q.calculateIdeologyCentrality = function(party, economicCoordinate, societalCoordinate) {
    var economic = Q.calculateEconomicIdeologyCentrality(party, economicCoordinate);
    var societal = Q.calculateSocietalIdeologyCentrality(party, societalCoordinate);
    return (economic + societal) / 2;
};
