Q.getFactionCoefficient = function(factionId, demographic) {
    var definition = Q.getFactionDefinition(factionId);
    if (!definition) {
        return 0;
    }
    var coefficients = Q.factionDemographicCoefficients[definition.originParty];
    if (!coefficients) {
        return 0;
    }
    var factionCoefficients = coefficients[definition.faction];
    if (!factionCoefficients) {
        return 0;
    }
    return Number(factionCoefficients[demographic]) || 0;
};
Q.getFactionBaseline = function(factionId) {
    var definition = Q.getFactionDefinition(factionId);
    if (!definition) {
        return 0;
    }
    if (!Q.factionStrengthBaseline[definition.originParty]) {
        return 0;
    }
    return Number(Q.factionStrengthBaseline[definition.originParty][definition.faction]) || 0;
};
Q.calculateFactionDemographicFactor = function(party, factionId) {
    var total = 0;
    for (var demographic of Q.demographicCategories) {
        var partyValue = Q.getPartyDemographicValue(party, demographic);
        var coefficient = Q.getFactionCoefficient(factionId, demographic);
        total += partyValue * coefficient;
    }
    return total;
};
Q.calculateFactionDemographicShare = function(party, factionId, demographic, strengthOverride) {
    var factionStrength;
    if (strengthOverride !== undefined) {
        factionStrength = strengthOverride;
    } 
else {
        factionStrength = Q.factionStrength[factionId] || 0;
    }
    var numerator =
        factionStrength *
        Q.getFactionCoefficient(factionId, demographic);
    var denominator = 0;
    for (var otherFaction of Q.getPartyFactions(party)) {
        var otherStrength = Q.factionStrength[otherFaction] || 0;
        var otherCoefficient = Q.getFactionCoefficient(otherFaction, demographic);
        denominator += otherStrength * otherCoefficient;
    }
    if (denominator <= 0) {
        return 0;
    }
    return numerator / denominator;
};

