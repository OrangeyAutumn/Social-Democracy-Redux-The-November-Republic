Q.transferFactionClassVotes = function(oldParty, targetParty, factionId, strengthOverride) {
    var transferred = {};
    for (var demographic of Q.demographicCategories) {
        var oldVariable = demographic + "_" + oldParty;
        var targetVariable = demographic + "_" + targetParty;
        var oldVotes = Number(Q[oldVariable]) || 0;
        var factionShare = Q.calculateFactionDemographicShare(oldParty, factionId, demographic, strengthOverride);
        var amount = oldVotes * factionShare;
        // Never transfer a negative amount.
        amount = Math.max(0, amount);
        amount = Math.min(amount, oldVotes);
        Q[oldVariable] = oldVotes - amount;
        Q[targetVariable] =  (Number(Q[targetVariable]) || 0) + amount;
        transferred[demographic] = amount;
    }
    return transferred;
};
