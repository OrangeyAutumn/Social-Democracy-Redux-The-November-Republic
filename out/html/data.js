Q.getAvailableIdeologies = function(party) {
    var available = [];
    for (var factionId of Q.getPartyFactions(party)) {
        var definition = Q.getFactionDefinition(factionId);
        if (!definition) {
            continue;
        }
        var originParty = definition.originParty;
        var faction = definition.faction;
        if (!Q.ideologyData || !Q.ideologyData[originParty] || !Q.ideologyData[originParty][faction]) {
            continue;
        }
        available.push({
            faction: factionId,
            originParty: originParty,
            data: Q.ideologyData[originParty][faction]
        });
    }
    return available;
};
Q.activateFormable = function(formableId, joiningFactions) {
    var formable = Q.formableData[formableId];
    if (!formable) {
        return false;
    }
    if (!joiningFactions || joiningFactions.length == 0) {
        return false;
    }
    var transfers = [];
    for (var factionId of joiningFactions) {
        if (formable.potential_factions.indexOf(factionId) == -1) {
            continue;
        }
        var currentOwner = Q.factionOwnership[factionId];
        if (currentOwner && currentOwner != formable.base_party) {
            transfers.push({
                faction: factionId,
                targetParty: formable.base_party
            });
        }
    }
    if (transfers.length == 0) {
        return false;
    }
    Q.moveFactions(transfers);
    return true;
};
