Q.calculateFactionLeadershipModifier = function(factionId, context) {
    if (!context || !context.leader_factions) {
        return 0;
    }
    var leaders = context.leader_factions;
    if (leaders.length == 0) {
        return 0;
    }
    var factionLeaders = 0;
    for (var leaderFaction of leaders) {
        if (leaderFaction == factionId) {
            factionLeaders += 1;
        }
    }
    if (factionLeaders == 0) {
        return 0;
    }
    return 0.15 *
        (factionLeaders / leaders.length);
};
Q.calculateFactionPoliticalModifier = function(party, factionId, context) {
    if (!context) {
        context = {};
    }
    var modifier = 0;
    if (Q.factionIsInArray(factionId, context.leader_factions)) {
        if (context.electoral_reference_modifier !== undefined) {
            modifier += context.electoral_reference_modifier;
        }
        if (context.electoral_change_modifier !== undefined) {
            modifier += context.electoral_change_modifier;
        }
    }
    if (Q.factionIsInArray(factionId, context.government_factions)) {
        modifier += 0.05;
    }
    if (context.chancellor_faction && context.chancellor_faction == factionId) {
        modifier += 0.05;
    }
    if (context.president_faction && context.president_faction == factionId) {
        modifier += 0.05;
    }
    if (context.coalition_modifiers && context.coalition_modifiers[factionId] !== undefined) {
        modifier += Number(context.coalition_modifiers[factionId]) || 0;
    }
    return modifier;
};
// FACTION STRENGTH
Q.calculateFactionRawStrength = function(party, factionId, context) {
    var baseline = Q.getFactionBaseline(factionId);
    if (baseline <= 0) {
        return 0;
    }
    var demographicFactor = Q.calculateFactionDemographicFactor(party, factionId);
    var politicalModifier = Q.calculateFactionPoliticalModifier(party, factionId, context);
    var leadershipModifier = Q.calculateFactionLeadershipModifier(factionId, context);
    var factionModifier = 1 + politicalModifier + leadershipModifier;
    return baseline * demographicFactor * factionModifier;
};
Q.recalculatePartyFactionStrength = function(party, context) {
    if (!context) {
        context = Q.factionStrengthContext[party] || {};
    }
    Q.factionStrengthContext[party] = context;
    var raw = {};
    var total = 0;
    for (var factionId of Q.getPartyFactions(party)) {
        var rawStrength = Q.calculateFactionRawStrength(party, factionId, context);
        raw[factionId] = rawStrength;
        total += rawStrength;
    }
    for (var factionId of Q.getPartyFactions(party)) {
        if (total > 0) {
            Q.factionStrength[factionId] =
                raw[factionId] / total * 100;
        } 
else {
            Q.factionStrength[factionId] = 0;
        }
    }
    Q.syncFactionVariables(party);
};
