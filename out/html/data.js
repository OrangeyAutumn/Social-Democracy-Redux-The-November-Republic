Q.convertPartyCoordinatesToIdeology = function(party, economicCoordinate, societalCoordinate) {
    var available = Q.getAvailableIdeologies(party);
    if (available.length == 0) {
        return "Unclassified";
    }
    var economicEntry = Q.getClosestIdeologyEntry(available, economicCoordinate);
    if (!economicEntry) {
        return "Unclassified";
    }
    var societalBand = Q.getSocietalIdeologyBand(party, societalCoordinate);
    if (societalBand === null || economicEntry.data.societal_label === undefined) {
        return economicEntry.data.economic_label;
    }
      var societalLabels = ["liberal", "democratic", "authoritarian"];
      return economicEntry.data.societal_label[societalLabels[societalBand]]; 
};
Q.getClosestIdeologyEntry = function(available, coordinate) {
    var best = null;
    var bestDistance = Infinity;
    for (var entry of available) {
        var definition = Q.getFactionDefinition(entry.faction);
        if (!definition) {
            continue;
        }
        var coordinateTable = Q.factionEconomicCoordinates[definition.originParty];
        if (!coordinateTable) {
            continue;
        }
        var anchor = coordinateTable[definition.faction];
        if (anchor === undefined) {
            continue;
        }
        var distance = Math.abs(coordinate - anchor);
        if (distance < bestDistance) {
            bestDistance = distance;
            best = entry;
        }
    }
    return best;
};
